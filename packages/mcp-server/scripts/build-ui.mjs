// Bundles ui/sound-picker.ts (with the MCP Apps client) into ui/sound-picker.html and
// writes the result as a string module, so the stdio server, its single-file bundle
// and the hosted server all serve the same self-contained page without a CDN.

import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url);
const path = (relative) => fileURLToPath(new URL(relative, root));

const result = await build({
  entryPoints: [path('ui/sound-picker.ts')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  legalComments: 'none',
  write: false,
});

// a literal </script> inside the bundle would end the inline script early
const script = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const template = await readFile(path('ui/sound-picker.html'), 'utf8');
if (!template.includes('<!-- APP_SCRIPT -->')) throw new Error('ui/sound-picker.html lost its <!-- APP_SCRIPT --> marker');
// a replacer function, so $ sequences in the minified bundle are not read as patterns
const html = template.replace('<!-- APP_SCRIPT -->', () => `<script>${script}</script>`);

await mkdir(path('src/generated'), { recursive: true });
await writeFile(
  path('src/generated/sound-picker-html.ts'),
  `// Generated by scripts/build-ui.mjs from ui/sound-picker.*; do not edit.\nexport const SOUND_PICKER_HTML = ${JSON.stringify(html)};\n`
);
console.log(`sound picker: ${(html.length / 1024).toFixed(0)} KB`);
